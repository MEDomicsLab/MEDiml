    df = pd.read_csv(csv_path)
    
    print(f"\nOriginal dataset: {len(df)} rows")
    print(f"Available modalities: {df['ImagingModality'].unique().tolist()}")
    
    # Filter to CT only
    df_ct_only = df[df['ImagingModality'] == 'CTscan'].copy()
    
